-- ---------------------------------------------------------------------------------------------
-- 1. "Which business is this request for?"
--    The API sets app.tenant_id at the start of every database transaction
--    (SELECT set_config('app.tenant_id', '<uuid>', true)).
--    If it was never set, these functions return NULL, and NULL never equals anything, so the
--    request sees NO rows and can write NO rows. Forgetting to set it fails closed, not open.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_current_tenant_id() RETURNS uuid
  LANGUAGE sql STABLE
  AS $$ SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid $$;

CREATE OR REPLACE FUNCTION app_current_user_id() RETURNS uuid
  LANGUAGE sql STABLE
  AS $$ SELECT NULLIF(current_setting('app.user_id', true), '')::uuid $$;

-- ---------------------------------------------------------------------------------------------
-- 2. enable_tenant_rls(table, column): the ONE way to protect a tenant table.
--    Call it at the end of every migration that creates a table with a tenant_id column:
--        SELECT enable_tenant_rls('products');
--    For the tenants table itself the "owner" column is its own id:
--        SELECT enable_tenant_rls('tenants', 'id');
--    What it does:
--      ENABLE  turns on row-level security for the table.
--      FORCE   applies it to the table's owner as well (otherwise the owner would skip it).
--      POLICY  a row is visible/writable only when its tenant column equals app.tenant_id.
--              USING covers reading, updating and deleting; WITH CHECK covers inserting and the
--              new values of an update (so a request cannot write a row into another business).
--    (SELECT app_current_tenant_id()) is wrapped in a sub-select so PostgreSQL evaluates it once
--    per query instead of once per row.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION enable_tenant_rls(target regclass, tenant_column name DEFAULT 'tenant_id')
  RETURNS void
  LANGUAGE plpgsql
  AS $$
BEGIN
  EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', target);
  EXECUTE format('ALTER TABLE %s FORCE ROW LEVEL SECURITY', target);
  EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %s', target);
  EXECUTE format(
    'CREATE POLICY tenant_isolation ON %s USING (%I = (SELECT app_current_tenant_id())) WITH CHECK (%I = (SELECT app_current_tenant_id()))',
    target, tenant_column, tenant_column
  );
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 3. app_grant_defaults(): give the app role its day-to-day rights (read/insert/update/delete rows)
--    on every table. Call it at the end of every migration that creates tables.
--    Rights that must be narrower (for example append-only audit tables) are revoked afterwards
--    in the migration that creates those tables.
--    The app role is never given the right to change structure, and never sees Prisma's own
--    bookkeeping table.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_grant_defaults(app_role name DEFAULT 'dumbbill_app')
  RETURNS void
  LANGUAGE plpgsql
  AS $$
BEGIN
  EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO %I', app_role);
  EXECUTE format('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO %I', app_role);
  IF to_regclass('public._prisma_migrations') IS NOT NULL THEN
    EXECUTE format('REVOKE ALL ON TABLE public._prisma_migrations FROM %I', app_role);
  END IF;
END
$$;

-- These two are build-time tools, not something request code should ever call.
REVOKE ALL ON FUNCTION enable_tenant_rls(regclass, name) FROM PUBLIC;
REVOKE ALL ON FUNCTION app_grant_defaults(name) FROM PUBLIC;

