-- ---------------------------------------------------------------------------------------------
-- 1. app_grant_defaults() learns about append-only tables.
--    Every migration calls app_grant_defaults(), which grants UPDATE and DELETE on ALL tables. Without
--    this change the next migration would silently give the app role back the right to rewrite the audit
--    log. Now the function itself removes UPDATE/DELETE again for every table on the list below.
--    ADD NEW APPEND-ONLY TABLES TO THIS LIST (stock_ledger, points_ledger, ... when they are created).
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_grant_defaults(app_role name DEFAULT 'dumbbill_app')
  RETURNS void
  LANGUAGE plpgsql
  AS $$
DECLARE
  append_only text[] := ARRAY['audit_log'];
  t text;
BEGIN
  EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO %I', app_role);
  EXECUTE format('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO %I', app_role);
  IF to_regclass('public._prisma_migrations') IS NOT NULL THEN
    EXECUTE format('REVOKE ALL ON TABLE public._prisma_migrations FROM %I', app_role);
  END IF;
  FOREACH t IN ARRAY append_only LOOP
    IF to_regclass('public.' || t) IS NOT NULL THEN
      EXECUTE format('REVOKE UPDATE, DELETE, TRUNCATE ON TABLE public.%I FROM %I', t, app_role);
    END IF;
  END LOOP;
END
$$;
REVOKE ALL ON FUNCTION app_grant_defaults(name) FROM PUBLIC;

