-- 4. Login by email, before the business is known.
--
--    PROBLEM: to log in, the API must find a user by email, but row-level security hides every row until
--    the business is known, and the business is exactly what login has to discover.
--    ANSWER: one narrow function that returns only the handful of fields login needs, for ONE exact email.
--    The app role is never given a general "see all businesses" ability (ADR 002 section 3).
--
--    HOW IT WORKS: the function runs with the rights of a special role, dumbbill_auth, which
--      - cannot log in, and has no bypass of row-level security,
--      - may read ONLY the listed columns of users (no tokens, no TOTP secrets),
--      - has its own policy on users that lets it see all rows (rows only, only for that role).
--    Because users has FORCE row-level security, a plain "function owned by the table owner" would see
--    nothing in production (a normal owner is bound by the policies too), so a dedicated role with an
--    explicit policy is the reliable design.
-- ---------------------------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dumbbill_auth') THEN
    CREATE ROLE dumbbill_auth NOLOGIN NOSUPERUSER NOBYPASSRLS NOINHERIT;
  END IF;
END
$$;

