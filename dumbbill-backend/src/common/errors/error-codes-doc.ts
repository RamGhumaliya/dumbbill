import { ERROR_CODES } from './error-codes';

/**
 * Builds the text of docs/api/error-codes.md from the error catalogue.
 * Kept in `src` (not in the script) so a unit test can check the committed file is up to date.
 */
export function renderErrorCodesMarkdown(): string {
  const rows = Object.entries(ERROR_CODES)
    .sort(([, a], [, b]) => a.status - b.status)
    .map(([code, info]) => `| \`${code}\` | ${info.status} | ${info.title} | ${info.uiHint} |`)
    .join('\n');

  return `<!-- GENERATED by \`pnpm docs:errors\` from src/common/errors/error-codes.ts. Do not edit by hand. -->
# API error codes

Every failed request returns the same JSON body (content type \`application/problem+json\`, RFC 9457):

\`\`\`json
{
  "type": "https://api.dumbbill.in/errors/discount-exceeds-limit",
  "title": "Discount exceeds your limit",
  "status": 422,
  "code": "DISCOUNT_EXCEEDS_LIMIT",
  "detail": "Maximum allowed is 5%.",
  "requestId": "01JA0000000000000000000000",
  "errors": [{ "field": "discount.value", "message": "must not be greater than 5" }]
}
\`\`\`

- **Decide behaviour from \`code\`**, never from \`title\` or \`detail\`. The text can change; codes are stable.
- **\`detail\`** is safe to show to the user. **\`errors[]\`** is present for validation problems: show each message next to its field.
- **\`requestId\`** is also in the \`X-Request-Id\` response header on every response, successful or not. When something unexpected happens (\`INTERNAL_ERROR\`), show it so the user can quote it to support.
- Another business's data always answers \`NOT_FOUND\`, never \`FORBIDDEN\`, so existence is never revealed.
- Send your own \`X-Request-Id\` (8-64 letters, digits, \`.\`, \`_\`, \`-\`) if you want one id to follow a user action across app and server.

| Code | HTTP | Title | What the app should do |
|---|---|---|---|
${rows}
`;
}
