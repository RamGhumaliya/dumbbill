import { contrastRatio } from './contrast';

/**
 * Reads the design tokens (docs/02-design/tokens/tokens.json), checks them, and produces the files
 * the web app uses:
 *
 *   src/styles/tokens.css          the colours of both themes as CSS variables, plus sizes and motion
 *   src/styles/tailwind-theme.css  tells Tailwind which colours, sizes and fonts exist (nothing else does)
 *   src/lib/design/token-names.ts  the names, for code that needs them (class merging, tests)
 *
 * The JSON is the single source of truth. The mobile app generates its own theme from the same file.
 * Everything here is a plain function so tests can run it without touching the disk.
 */

type ThemeName = 'dark' | 'light';

export interface TokenFile {
  meta: { name: string; version: string; themes: Record<ThemeName, string> };
  color: {
    roles: Record<string, { tailwind: string; use: string }>;
    dark: Record<string, string>;
    light: Record<string, string>;
  };
  contrast: Array<{ fg: string; bg: string; min: number; use: string }>;
  contrastNotRequired: Record<string, string>;
  font: Record<'ui' | 'numerals' | 'code', { family: string; fallback: string; use: string }>;
  fontSize: Record<string, number>;
  radius: Record<string, number>;
  focus: { width: number; offset: number };
  size: Record<string, number>;
  motion: {
    duration: Record<string, number>;
    easing: Record<string, string>;
    shift: number;
  };
}

const THEMES: ThemeName[] = ['dark', 'light'];
const HEX = /^#[0-9a-f]{6}$/i;
const RGBA = /^rgba\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*(0|1|0?\.\d+)\s*\)$/;

/** "bg.base" -> "bg-base": the CSS variable name for a colour role. */
export const cssVarName = (role: string): string => `--${role.replaceAll('.', '-')}`;

/** "controlSm" -> "control-sm". */
const kebab = (name: string): string =>
  name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/**
 * Check the token file is complete and consistent. Returns a list of problems (empty = fine).
 * It checks that every colour role has a value in BOTH themes, every value is a valid colour, every
 * Tailwind name is unique, and (most importantly) that every contrast pair meets its minimum in both themes.
 */
export function validateTokens(tokens: TokenFile): string[] {
  const problems: string[] = [];
  const roles = Object.keys(tokens.color.roles);

  for (const theme of THEMES) {
    const values = tokens.color[theme];
    for (const role of roles) {
      const value = values[role];
      if (value === undefined) problems.push(`${theme}: role "${role}" has no colour.`);
      else if (!HEX.test(value) && !RGBA.test(value))
        problems.push(`${theme}: "${role}" is not a valid colour: ${value}`);
    }
    for (const role of Object.keys(values)) {
      if (!roles.includes(role)) problems.push(`${theme}: "${role}" is not a declared role.`);
    }
  }

  const names = roles.map((role) => tokens.color.roles[role]?.tailwind);
  if (new Set(names).size !== names.length)
    problems.push('Two colour roles share the same Tailwind name.');

  for (const { fg, bg, min, use } of tokens.contrast) {
    for (const theme of THEMES) {
      const a = tokens.color[theme][fg];
      const b = tokens.color[theme][bg];
      if (a === undefined || b === undefined) {
        problems.push(`contrast pair "${fg}" on "${bg}" refers to an unknown role.`);
        break;
      }
      if (!HEX.test(a) || !HEX.test(b)) continue; // translucent colours cannot be measured on their own
      const ratio = contrastRatio(a, b);
      if (ratio < min) {
        problems.push(
          `${theme}: ${fg} (${a}) on ${bg} (${b}) is ${ratio.toFixed(2)}:1 but needs ${min}:1 (${use}).`,
        );
      }
    }
  }

  // Every role must be covered by a contrast check or be explicitly excused, so a new colour cannot slip in unchecked.
  const covered = new Set([
    ...tokens.contrast.flatMap((pair) => [pair.fg, pair.bg]),
    ...Object.keys(tokens.contrastNotRequired),
  ]);
  for (const role of roles) {
    if (!covered.has(role))
      problems.push(
        `role "${role}" has no contrast check. Add a pair or list it in contrastNotRequired.`,
      );
  }
  return problems;
}

/** The contrast ratios of every pair in both themes, for a readable report. */
export function contrastReport(
  tokens: TokenFile,
): Array<{ theme: ThemeName; fg: string; bg: string; ratio: number; min: number }> {
  return THEMES.flatMap((theme) =>
    tokens.contrast.flatMap(({ fg, bg, min }) => {
      const a = tokens.color[theme][fg];
      const b = tokens.color[theme][bg];
      return a && b && HEX.test(a) && HEX.test(b)
        ? [{ theme, fg, bg, ratio: contrastRatio(a, b), min }]
        : [];
    }),
  );
}

const BANNER = (target: string): string =>
  `GENERATED by \`pnpm tokens\` from docs/02-design/tokens/tokens.json. DO NOT EDIT BY HAND.\n * Change the JSON and regenerate. (${target})`;

/** One theme's colour declarations, indented by `indent` spaces. */
function colourBlock(tokens: TokenFile, theme: ThemeName, indent: number): string {
  const pad = ' '.repeat(indent);
  const values = tokens.color[theme];
  return [
    `${pad}color-scheme: ${theme};`,
    ...Object.keys(tokens.color.roles).map((role) => `${pad}${cssVarName(role)}: ${values[role]};`),
  ].join('\n');
}

/** src/styles/tokens.css */
export function renderTokensCss(tokens: TokenFile): string {
  const { duration, shift } = tokens.motion;
  const sizes = Object.entries(tokens.size).map(
    ([name, px]) => `  --size-${kebab(name)}: ${px}px;`,
  );
  const durations = Object.entries(duration).map(([name, ms]) => `  --duration-${name}: ${ms}ms;`);

  return `/*
 * ${BANNER('colours, sizes and motion as CSS variables')}
 *
 * ${tokens.meta.themes.light} (light) is the default. ${tokens.meta.themes.dark} (dark) applies when the user chose
 * dark, or when they chose nothing and the device is set to dark. The dark values appear twice because CSS
 * cannot share one block between a media query and an attribute selector.
 */

:root {
${colourBlock(tokens, 'light', 2)}

  /* Sizes that are not colours. Components use these through classes such as min-h-(--size-control-md). */
${sizes.join('\n')}
  --focus-ring-width: ${tokens.focus.width}px;
  --focus-ring-offset: ${tokens.focus.offset}px;

  /* Motion */
${durations.join('\n')}
  --motion-shift: ${shift}px;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${colourBlock(tokens, 'dark', 4)}
  }
}

:root[data-theme='dark'] {
${colourBlock(tokens, 'dark', 2)}
}
`;
}

/** src/styles/tailwind-theme.css */
export function renderTailwindTheme(tokens: TokenFile): string {
  const colours = Object.entries(tokens.color.roles).map(
    ([role, { tailwind }]) => `  --color-${tailwind}: var(${cssVarName(role)});`,
  );
  const radii = Object.entries(tokens.radius).map(([name, px]) => `  --radius-${name}: ${px}px;`);
  const sizes = Object.entries(tokens.fontSize).map(([name, px]) => `  --text-${name}: ${px}px;`);
  const easings = Object.entries(tokens.motion.easing).map(
    ([name, curve]) => `  --ease-${name}: ${curve};`,
  );
  const f = tokens.font;

  return `/*
 * ${BANNER('the only colours, sizes and fonts Tailwind knows about')}
 *
 * Tailwind's built-in colours, corner radii, text sizes, shadows and easings are switched off (\`initial\`)
 * and replaced by ours. A developer cannot write bg-blue-500 or rounded-3xl: those classes do not exist.
 * This is how the product is kept from drifting into a default-template look.
 */
@theme static {
  /* Colours (the values live in tokens.css and change with the theme) */
  --color-*: initial;
${colours.join('\n')}
  --color-transparent: transparent;
  --color-current: currentColor;

  /* Corners: two radii only */
  --radius-*: initial;
${radii.join('\n')}

  /* Type scale */
  --text-*: initial;
${sizes.join('\n')}

  /* No shadows: the design uses borders for structure */
  --shadow-*: initial;

  /* Easing curves */
  --ease-*: initial;
${easings.join('\n')}

  /* Fonts. Each stack lists its own Latin file, then its Latin-extended file, then Inter Tight, then the system font.
     Why Inter Tight again at the end of the numerals and code stacks: Barlow Condensed and JetBrains Mono have NO
     rupee sign (U+20B9). Every price in this product starts with one, so without this the browser would pick a random
     system font for the rupee next to our own digits. Inter Tight (variable weight, so it matches bold totals) does
     contain it. The browser uses a font only for the characters the earlier ones lack. */
  --font-sans: var(--font-ui-latin), var(--font-ui-ext), ${f.ui.fallback};
  --font-display: var(--font-numerals-latin), var(--font-numerals-ext), var(--font-ui-latin), var(--font-ui-ext), ${f.numerals.fallback};
  --font-mono: var(--font-code-latin), var(--font-code-ext), var(--font-ui-latin), var(--font-ui-ext), ${f.code.fallback};
}
`;
}

/** src/lib/design/token-names.ts */
export function renderTokenNames(tokens: TokenFile): string {
  const colours = Object.values(tokens.color.roles).map((role) => role.tailwind);
  const list = (items: string[]): string => `[${items.map((item) => `'${item}'`).join(', ')}]`;

  return `/**
 * ${BANNER('names of the design tokens, for code')}
 *
 * Used by the class-name merger (so it understands our custom class names) and by tests.
 */

/** Colour names usable in classes: bg-<name>, text-<name>, border-<name> ... */
export const COLOR_NAMES = ${list(colours)} as const;

/** Every colour role: its design name, Tailwind name, CSS variable and purpose. Used by the design gallery. */
export const COLOR_ROLES = ${JSON.stringify(
    Object.entries(tokens.color.roles).map(([role, info]) => ({
      role,
      tailwind: info.tailwind,
      cssVar: cssVarName(role),
      use: info.use,
    })),
    null,
    2,
  )} as const;

/** Font-size names usable as text-<name>. */
export const FONT_SIZE_NAMES = ${list(Object.keys(tokens.fontSize))} as const;

/** Corner radius names usable as rounded-<name>. */
export const RADIUS_NAMES = ${list(Object.keys(tokens.radius))} as const;
`;
}

/** Every generated file: path (relative to the web app folder) -> contents. */
export function generateAll(tokens: TokenFile): Record<string, string> {
  return {
    'src/styles/tokens.css': renderTokensCss(tokens),
    'src/styles/tailwind-theme.css': renderTailwindTheme(tokens),
    'src/lib/design/token-names.ts': renderTokenNames(tokens),
  };
}
